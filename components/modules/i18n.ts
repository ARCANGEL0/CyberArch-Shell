// fill gaps: any Lang missing a key falls back to EN via t()
for (const l of LANG_ORDER) {
  if (!langs[l]) langs[l] = {}
  for (const k of Object.keys(EN)) {
    if (langs[l][k] === undefined) langs[l][k] = EN[k]
  }
}

let langCurrent: Lang = "en"
const changeBus: Array<() => void> = []
export const onLangChange = (cb: () => void): (() => void) => {
  changeBus.push(cb)
  return () => { const i = changeBus.indexOf(cb); if (i >= 0) changeBus.splice(i, 1) }
}
export const notifyLangChange = () => { for (const cb of [...changeBus]) { try { cb() } catch (e) { print("[i18n] notify:", e) } } }

export const getLang = (): Lang => langCurrent
export const setLang = (lang: Lang): void => {
  if (!LANG_ORDER.includes(lang)) return
  langCurrent = lang
  notifyLangChange()
}

export const t = (key: string, lang?: Lang): string => {
  const l = lang ?? langCurrent
  return langs[l]?.[key] ?? EN[key] ?? key
}

export const langFont = (lang: Lang): string => FONT_BY_LANG[lang] ?? ""
